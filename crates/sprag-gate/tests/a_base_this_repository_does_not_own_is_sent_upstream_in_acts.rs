//! ⛔⛔⛔⛔⛔ **A BASE THIS REPOSITORY DOES NOT OWN IS SENT UPSTREAM, AND EVERY WORKING TURN IS TOLD
//! SO IN ACTS** — register item 1037, the WORDS half.
//!
//! # ⛔⛔⛔⛔⛔ The defect: a clause with consequences that nothing re-read
//!
//! The owner's ruling of 2026-09-11 put a sentence into a working turn — *if the base is UPSTREAM of
//! this repository, do not patch it here: register what you found, then ask a question and stop* —
//! and **nothing anywhere went red when it was deleted, reworded, or simply not sent.** That is the
//! shape register item 936 already named and this workspace's rule 10 is about: the predicate with
//! the largest consequence in the loop becomes the sentence nobody measures. `smallest` had lived in
//! the same slot for four weeks with no gate and no recorded argument, which is how it came to be
//! deleted rather than defended.
//!
//! # ⚠⚠⚠⚠⚠ The population is the THREE ROADS INTO A WORKING TURN, and it was measured
//!
//! A gate over `turn_prompt` alone is an exemption nobody wrote down. Asked of the document
//! 2026-09-11, the prompts a WORKING turn can arrive under are three — `start_prompt` (a session's
//! first turn), `turn_prompt` (every turn after it) and `changed_prompt` (a live session handed a
//! new checkpoint) — and **exactly one of them carried the clauses.** With this repository's kind
//! replacing its session every five turns, the road that never carried them is not a corner: every
//! fresh session's first turn, and every turn after a reflection moved the milestone, was told
//! nothing about where a fix goes. The repair is `where_to_fix`, composed once and read by all
//! three, and this gate is what holds it there.
//!
//! # ⚠⚠⚠⚠ Why the needles are read from the UNCOMMENTED document, measured rather than assumed
//!
//! The argument FOR each clause is written beside it, and it quotes the clause. So a scan of the raw
//! file finds every needle whether or not a single prompt still carries one — the vacuous green
//! register item 799 measured, arriving through a comment. [`assert_the_reader_is_not_reading_the_argument`]
//! is that hazard asserted rather than avoided, in two claims: the stripper is shown to WORK, on a
//! needle no prompt can contain, and each act is then required to survive it **exactly once** —
//! because `where_to_fix` exists so that one ruling has one source, and a second copy is where the
//! three roads start to disagree.
//!
//! ⚠ The first draft of that control required each needle to appear MORE times raw than stripped,
//! which holds the PROSE to quoting the clauses rather than holding the document to sending them. It
//! went red the moment a comment was rewritten without a quotation — a gate about the commentary's
//! wording, which is not what any of this is for.
//!
//! # ⚠⚠ This is the WORDS half. The DEED has its own arm
//!
//! `sprag_plugin`'s `a_turn_that_met_a_base_upstream_left_a_record_and_stood_and_an_ordinary_one_did_neither`
//! drives a run whose peer meets such a base and reads what it DID — which of the marks its work is
//! supposed to move it moved, and whether it stopped. Neither half is the other: this one goes red
//! when the sentence stops being sent, and that one goes red when a run stands without registering.

use sprag_gate::loop_shape::{Composed, DOCUMENT, composed_prompts, uncommented};
use sprag_gate::sources::workspace_root;

/// **THE PROMPTS A WORKING TURN CAN ARRIVE UNDER**, each with what makes it one.
///
/// ⚠⚠⚠ A LIST OF THREE AND NOT A RULE ABOUT NAMES, on `MAY_NAME_IT`'s terms one gate over: a fourth
/// entry is a decision somebody has to make, and it must be made with the reason beside it.
///
/// * `start_prompt` GREETS a freshly opened session — and the turn it opens is a working turn, which
///   is the half that was missing. It is also the road a REPLACEMENT takes (`restarting`), so a run
///   that reflects every five turns arrives here over and over.
/// * `turn_prompt` is every turn after the first. `dispute_prompt` and `unverified_prompt` compose it
///   IN, so they carry whatever it carries and are not separate roads.
/// * `changed_prompt` is a LIVE session handed a new checkpoint — register item 800's second half.
///   It is a working turn for the same reason `turn_prompt` is: the agent reads it and then works.
const A_WORKING_TURN_ARRIVES_UNDER: [&str; 3] = ["start_prompt", "turn_prompt", "changed_prompt"];

/// **THE PROMPTS THAT ASK ABOUT THE WORK RATHER THAN DOING IT**, which must NOT carry the clauses.
///
/// ⚠⚠ THE CONTRAST, and it is what keeps the claim above from being *every prompt says everything*.
/// A reflection is the loop asking its agent where to aim next and an ending is asking what happened;
/// neither opens a turn in which anything is fixed, so a ruling about where a fix goes retyped into
/// them is the cost register item 800 measured — bytes re-sent at a session that cannot act on them.
const ASKS_RATHER_THAN_WORKS: [&str; 4] = [
    "reflect_prompt",
    "reask_prompt",
    "end_prompt",
    "stop_prompt",
];

/// **THE PROMPTS THAT COMPOSE A WORKING ONE IN**, so they carry the clauses without naming the part.
///
/// ⚠ Named rather than assumed: each is `turn_prompt` with an opening in front of it, and a round
/// that flattened one into its own literal would leave this gate green while that road went silent.
const COMPOSE_A_WORKING_ONE: [&str; 2] = ["dispute_prompt", "unverified_prompt"];

/// **THE PARTS THE THREE ROADS READ**, each spelled once in the document and once here.
///
/// # ⛔⛔⛔⛔⛔ Why this is a SET and was a single name until register item 1068
///
/// One part was one ruling, and the file has two. Item 1068's is the other arm of an axis this
/// document had exactly one of: `where_to_fix` tells a working turn to *ask a question and stop*
/// when the base is upstream, and nothing told it when NOT to ask — so the owner's rule against
/// handing over a decision the criteria already settle reached no run at all.
///
/// ⚠⚠ **A SECOND PART RATHER THAN THREE MORE CLAUSES ON THE FIRST**, which is this gate's own
/// argument applied one level up: `where_to_fix` is named for where a fix goes, and one ruling has
/// one source. Two rulings in one part is where the name stops saying what the value holds.
///
/// ⚠ Everything below walks this list, so a third part is one entry here and one `<assign>` there —
/// and a part added to the document and not to this list is a ruling no road is held to.
const THE_PARTS: [&str; 2] = [RULINGS[0].0, RULINGS[1].0];

/// **THE THREE ACTS THE CLAUSE ASKS FOR**, each with the fact that answers whether it happened.
///
/// # ⛔⛔⛔⛔⛔ Why the needle is the ACT and not the word `upstream`
///
/// Register item 1037's own ⑴ forbids the obvious predicate: *did the word appear* is a sentence
/// about a sentence, and it would be green over a prompt that said `upstream` and asked for nothing.
/// What each needle quotes is the IMPERATIVE — a thing a run either did or did not do — and the
/// right-hand column is where a run is asked about it, which is the deed arm's subject rather than
/// this one's.
const RULINGS: [(&str, &[(&str, &str)]); 2] = [
    (
        "where_to_fix",
        &[
            (
                "do not patch it here",
                "the turn moved no mark standing for this tree — `outer::Moved`",
            ),
            (
                "register what you found",
                "the turn moved the mark standing for the record — `outer::Moved`",
            ),
            (
                "ask a question and stop",
                "the run ended at a person — `OutcomeState::Blocked`, through `screening`'s \
                 `screen.none`",
            ),
        ],
    ),
    // ── REGISTER ITEM 1068: the other arm of the axis the part above opens ────────────────────
    (
        "when_to_ask",
        &[
            // ⛔⛔⛔⛔⛔ THE BAN. `ask a question and stop` above is the one case this document
            // ever named for stopping, and a run told that and nothing else has been told when to
            // knock and never when not to. The owner gave the missing half three times
            // (R311ob/pt/pw) and it lived in an agent's MEMORY — which a loop's agent does not
            // have — so no run ever carried it.
            (
                "Do not hand a person a decision your own criteria already settle",
                "the run did not end at a person over something its own brief decided",
            ),
            // ⚠⚠⚠⚠⚠ THE TELL, AND IT IS AN ACT BECAUSE THE AGENT PERFORMS IT ON ITSELF. *Is this
            // derivable* is not a question any predicate in this workspace can answer; *am I
            // splitting these options by what they cost* is one the party writing the options can.
            // ⚠ Measured as WORDS on purpose: the run this item was filed for offered three
            // options and NOT ONE of them named a cost, so a lexical detector would have been
            // green on the very sample it was filed from — register item 453's blind ratchet,
            // arriving before it was built.
            (
                "if you are splitting them by what they cost",
                "nothing measures this at run time, and `when_to_ask`'s declaration says why",
            ),
            // ⛔⛔⛔⛔ THE EXEMPTION, AND IT IS THE CONTROL. Without it the ban degenerates into
            // *never ask*, which is green over a document that has deleted the door
            // `ask a question and stop` opens — a worse run than the one this item is about,
            // arriving as its repair.
            (
                "Stop and ask only for a fork that is genuinely theirs",
                "a run standing on somebody's taste or scope is untouched — the control arm",
            ),
        ],
    ),
];

/// The document's text, read from the tree this run is standing in.
fn document_text() -> String {
    let path = workspace_root().join(DOCUMENT);
    std::fs::read_to_string(&path)
        .unwrap_or_else(|why| panic!("{DOCUMENT} is this workspace's loop: {why}"))
}

#[test]
fn every_prompt_a_working_turn_arrives_under_says_where_a_fix_goes() {
    let text = document_text();
    let composed = composed_prompts(&text);

    // ══ THE PREMISE: the reader can see prompts at all ═════════════════════════════════════════
    //
    // ⚠⚠⚠⚠⚠ Without it every verdict below is a statement about the empty list — register item
    // 799's vacuous green, which this workspace has now measured four times.
    assert!(
        composed.len() >= A_WORKING_TURN_ARRIVES_UNDER.len() + ASKS_RATHER_THAN_WORKS.len(),
        "⚠⚠⚠⚠⚠ THE SCAN IS BLIND: this document composes {} prompt(s), fewer than the {} this gate \
         has rulings for. Either the naming convention moved or the walk is reading a tree that is \
         not this one (register item 809). Read: {composed:?}",
        composed.len(),
        A_WORKING_TURN_ARRIVES_UNDER.len() + ASKS_RATHER_THAN_WORKS.len(),
    );

    // ══ AND THE POPULATION IS TOTAL: EVERY COMPOSED PROMPT IS RULED ON ════════════════════════
    //
    // ⛔⛔⛔⛔⛔ **THE THREE LISTS ABOVE ARE HAND-WRITTEN, AND A HAND-WRITTEN POPULATION LEAKS.** This
    // gate's own subject is a ruling that reached one road in three because nobody asked how many
    // roads there were; a gate whose list of roads is also somebody's memory is the same defect one
    // layer up. So a composed prompt this file has no ruling for is RED — rule 6, and the exact
    // discipline `a_briefing_counts_every_part_the_door_was_handed` applies to the parts of a brief.
    //
    // ⚠⚠ MEASURED BEFORE IT WAS WRITTEN, so it goes in as a ratchet rather than as a repair: asked
    // of the document 2026-09-11, the three lists partition the nine composed prompts exactly —
    // nothing unruled, nothing ruled that is not composed, nothing on two lists.
    //
    // ⚠ AND THE DISJOINTNESS IS ASSERTED rather than left to contradict itself: a name on two lists
    // makes *must carry it* and *must not carry it* both true of one prompt, and whichever
    // assertion fires first prints a sentence about the wrong thing.
    let ruled = |name: &str| {
        usize::from(A_WORKING_TURN_ARRIVES_UNDER.contains(&name))
            + usize::from(ASKS_RATHER_THAN_WORKS.contains(&name))
            + usize::from(COMPOSE_A_WORKING_ONE.contains(&name))
    };
    let unruled: Vec<&str> = composed
        .iter()
        .map(|one| one.prompt.as_str())
        .filter(|name| ruled(name) == 0)
        .collect();
    assert!(
        unruled.is_empty(),
        "⛔⛔⛔⛔⛔ REGISTER ITEM 1037: {DOCUMENT} composes {unruled:?} and this gate has no ruling \
         for them. The next prompt somebody composes is exactly the one that would open a working \
         turn and say nothing about where a fix goes — which is the state this item was paid off \
         from, arriving through a list nobody held against the file. Put each one on \
         `A_WORKING_TURN_ARRIVES_UNDER`, `ASKS_RATHER_THAN_WORKS` or `COMPOSE_A_WORKING_ONE`, with \
         the reason beside it.",
    );
    let twice: Vec<&str> = composed
        .iter()
        .map(|one| one.prompt.as_str())
        .filter(|name| ruled(name) > 1)
        .collect();
    assert!(
        twice.is_empty(),
        "⚠⚠⚠ {twice:?} are on more than one of this gate's lists, so this file both requires and \
         forbids the same prompt to carry {THE_PARTS:?}",
    );

    let expr_of = |name: &str| -> String {
        composed
            .iter()
            .find(|one: &&Composed| one.prompt == name)
            .unwrap_or_else(|| panic!("{DOCUMENT} composes no `{name}`: {composed:?}"))
            .expr
            .clone()
    };

    // ══ THE PART ITSELF CARRIES ALL THREE ACTS ════════════════════════════════════════════════
    //
    // ⚠⚠⚠ **READ BY `assigned` AND NOT BY `composed_prompts`, AND THAT IS NOT A FALLBACK.**
    // `composed_prompts` collects `location`s ENDING in `prompt`; `where_to_fix` does not, by
    // design — a part is not a prompt, and widening that reader's convention to reach it would put
    // it into every population that walk feeds, starting with the partition asserted above.
    //
    // ⛔⛔ **THE FIRST DRAFT ASKED `composed_prompts` FIRST AND FELL BACK, AND THAT BRANCH WAS
    // DEAD** — measured rather than suspected: the name cannot satisfy that convention, so the
    // `find` could never hit and the fallback always ran. A dead branch shaped like a live one is
    // the hazard register item 799 keeps producing — rename the part to end in `prompt` and the
    // read silently changes road — and the `unwrap_or_default()` in front of it was the worse
    // half: a part this reader could not see arrived as an EMPTY STRING, and an empty string is a
    // value every *must not contain* assertion is trivially true of.
    let bare = uncommented(&text);
    for (the_part, acts) in RULINGS {
        let part = assigned(&bare, the_part);
        assert!(
            !part.is_empty(),
            "⚠⚠⚠⚠⚠ THE SCAN IS BLIND: `{the_part}` is assigned nothing this reader can see in \
             {DOCUMENT}, so every act asserted below would be asserted of an empty string",
        );
        for (act, answered_by) in acts {
            assert!(
                part.contains(act),
                "⛔⛔⛔⛔⛔ REGISTER ITEM 1037 (and 1068 for `when_to_ask`): `{the_part}` no longer \
                 asks a working turn to `{act}`. That act is what {answered_by} is read to check, \
                 so deleting the words leaves the arm measuring a run nobody told. Read: {part}",
            );
        }
    }

    // ══ AND EVERY ROAD INTO A WORKING TURN READS EVERY PART ════════════════════════════════════
    let mut silent = Vec::new();
    for name in A_WORKING_TURN_ARRIVES_UNDER {
        let expr = expr_of(name);
        for the_part in THE_PARTS {
            if !expr.contains(the_part) {
                silent.push(format!("{name} (no `{the_part}`)"));
            }
        }
    }
    assert!(
        silent.is_empty(),
        "⛔⛔⛔⛔⛔ REGISTER ITEM 1037: {silent:?} open a working turn and say nothing about where a \
         fix goes. Measured 2026-09-11, this is exactly the state the item was paid off from: the \
         three clauses were literals inside `turn_prompt`, so a session's FIRST turn and every turn \
         after a reflection moved the milestone were told none of them — and with `reflect_every` \
         at 5 that is one turn in five. An instruction one road in three never carries is an \
         exemption nobody wrote down.",
    );

    // ══ THE CONTRAST: a prompt that ASKS about the work must not be handed rulings for doing it ══
    //
    // ⚠⚠⚠⚠⚠ WITHOUT THIS ARM the claim above is satisfied by a document that pastes the part into
    // every prompt it has — which is register item 800's own cost (bytes re-sent at a session that
    // cannot act on them) bought back one round after it was paid.
    let mut retyped = Vec::new();
    for name in ASKS_RATHER_THAN_WORKS {
        let expr = expr_of(name);
        for the_part in THE_PARTS {
            if expr.contains(the_part) {
                retyped.push(format!("{name} (carries `{the_part}`)"));
            }
        }
    }
    assert!(
        retyped.is_empty(),
        "⚠⚠⚠⚠ {retyped:?} ask the agent ABOUT the work rather than opening a turn of it, and they \
         are being handed a ruling about where a fix goes. Register item 800 measured what retyping \
         at a session that cannot act on it costs.",
    );

    // ══ AND THE TWO THAT COMPOSE A WORKING PROMPT IN STILL DO ══════════════════════════════════
    //
    // ⚠⚠ They carry the clauses WITHOUT naming the part, so the claim about them is the composition
    // rather than the needle. A round that flattened one into its own literal would silence that
    // road while every assertion above stayed green.
    for name in COMPOSE_A_WORKING_ONE {
        let expr = expr_of(name);
        assert!(
            expr.contains("turn_prompt"),
            "⚠⚠⚠ `{name}` is sent to an agent that then WORKS, and it no longer composes \
             `turn_prompt` in — so whatever that prompt carries, this road has stopped carrying. \
             Read: {expr}",
        );
    }

    assert_the_reader_is_not_reading_the_argument(&text);
}

/// ⛔⛔⛔⛔⛔ **EACH ACT IS SENT FROM EXACTLY ONE PLACE, AND THE READER IS NOT READING THE ARGUMENT
/// FOR IT.**
///
/// # ⚠⚠⚠⚠⚠ Two hazards, and only one of them is about the stripper
///
/// * **THE COMMENTARY QUOTES THE CLAUSES**, because every clause in this document is argued for
///   beside itself. A reader that did not strip comments would find all three acts in a file whose
///   prompts had stopped carrying any of them — register item 799's vacuous green, arriving through
///   a comment. So the stripper is asserted to WORK, on a needle no prompt can contain.
/// * **A SECOND LITERAL COPY IS THE DEFECT [`THE_PARTS`] EXIST TO END.** Item 1037 found the three
///   clauses written out inside one prompt, and the repair is one part three roads read. If a later
///   round pastes them back into a prompt rather than reading the part, the roads can drift — and
///   the assertions above cannot see it, because they ask *does this expression carry the part* and
///   a hand-written copy answers the question a different way. **One occurrence is what says there
///   is one source.**
fn assert_the_reader_is_not_reading_the_argument(text: &str) {
    let bare = uncommented(text);
    // ⚠⚠ A NEEDLE NO PROMPT CAN CARRY, which is what makes this a control on the STRIPPER rather
    // than a claim about the prose: this document's commentary is marked with it and its prompts
    // are sentences typed at an agent.
    const ONLY_COMMENTARY_SAYS: &str = "⛔";
    assert!(
        text.contains(ONLY_COMMENTARY_SAYS),
        "⚠⚠⚠ THE CONTROL'S OWN PREMISE: {DOCUMENT}'s commentary is marked with \
         `{ONLY_COMMENTARY_SAYS}`, and a file without it is not the one this gate was written \
         against",
    );
    assert!(
        !bare.contains(ONLY_COMMENTARY_SAYS),
        "⚠⚠⚠⚠⚠ THE STRIPPER IS NOT STRIPPING: `{ONLY_COMMENTARY_SAYS}` marks this document's \
         commentary and it survived. Every needle below would then be found whether or not a single \
         prompt still carried it — which is the vacuous green register item 799 measured, arriving \
         through a comment.",
    );
    for (the_part, acts) in RULINGS {
        for (act, _) in acts {
            let sent = bare.matches(act).count();
            assert_eq!(
                sent, 1,
                "⛔⛔⛔⛔⛔ REGISTER ITEM 1037: `{act}` is sent from {sent} place(s) in {DOCUMENT}, \
                 and `{the_part}` exists so that it is sent from ONE. Zero means no working turn is \
                 told it at all; more than one means a road has its own copy, and two copies of one \
                 ruling are where the three roads come to disagree — which is the state this item \
                 was paid off from.",
            );
        }
    }
}

/// The `expr` of the `<assign location="…">` named, whitespace squeezed — [`composed_prompts`]'s own
/// reading, for a location its naming convention does not claim.
///
/// ⚠ It takes text a caller has ALREADY stripped comments from, so there is one definition of what a
/// comment is in this workspace and this is not a second one.
fn assigned(bare: &str, location: &str) -> String {
    let opens = format!("<assign location=\"{location}\"");
    let at = bare
        .find(&opens)
        .unwrap_or_else(|| panic!("{DOCUMENT} assigns no `{location}` outside its commentary"));
    let after = &bare[at..];
    let expr_at = after
        .find("expr=\"")
        .unwrap_or_else(|| panic!("`{location}` is assigned with no `expr` this reader can read"));
    let value = &after[expr_at + "expr=\"".len()..];
    let end = value
        .find('"')
        .unwrap_or_else(|| panic!("`{location}`'s `expr` never closes"));
    value[..end]
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
}
